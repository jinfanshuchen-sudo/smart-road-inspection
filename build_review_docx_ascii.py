def set_blue(run, bold=False, size=10.5):
    run.font.color.rgb = BLUE
    run.font.bold = bold
    run.font.size = Pt(size)
    run.font.name = "\u5b8b\u4f53"
    rpr = run._element.get_or_add_rPr()
    rpr.rFonts.set(qn("w:eastAsia"), "\u5b8b\u4f53")


def set_cell_blue(cell, text, bold=False):
    cell.text = ""
    p = cell.paragraphs[0]
    p.alignment = WD_ALIGN_PARAGRAPH.LEFT
    p.paragraph_format.space_after = Pt(0)
    run = p.add_run(text)
    set_blue(run, bold=bold, size=9)
    cell.vertical_alignment = WD_CELL_VERTICAL_ALIGNMENT.CENTER


def insert_paragraph_after(paragraph):
    element = OxmlElement("w:p")
    paragraph._p.addnext(element)
    return Paragraph(element, paragraph._parent)


def add_blue_after(anchor, text, bold=False, indent=False):
    p = insert_paragraph_after(anchor)
    p.paragraph_format.space_after = Pt(4)
    p.paragraph_format.line_spacing = 1.15
    if indent:
        p.paragraph_format.first_line_indent = Cm(0.74)
    run = p.add_run(text)
    set_blue(run, bold=bold)
    return p


def add_blue_lines(anchor, lines):
    current = anchor
    for text, bold, indent in lines:
        current = add_blue_after(current, text, bold=bold, indent=indent)
    return current


def add_table_after(anchor, headers, rows, widths=None):
    doc = anchor.part.document
    table = doc.add_table(rows=1, cols=len(headers))
    table.alignment = WD_TABLE_ALIGNMENT.CENTER
    table.style = "Table Grid"
    for idx, header in enumerate(headers):
        set_cell_blue(table.rows[0].cells[idx], header, bold=True)
    for row in rows:
        cells = table.add_row().cells
        for idx, value in enumerate(row):
            set_cell_blue(cells[idx], value)
    if widths:
        for row in table.rows:
            for idx, width in enumerate(widths):
                row.cells[idx].width = Cm(width)
    anchor._p.addnext(table._tbl)
    tail = OxmlElement("w:p")
    table._tbl.addnext(tail)
    return Paragraph(tail, anchor._parent)


def find_paragraph(doc, keyword):
    for p in doc.paragraphs:
        if keyword in p.text:
            return p
    print("WARN: anchor not found:", keyword)
    return None


def add_at(doc, keyword, lines, table=None):
    anchor = find_paragraph(doc, keyword)
    if anchor is None:
        return
    end = add_blue_lines(anchor, lines)
    if table:
        headers, rows, widths = table
        add_table_after(end, headers, rows, widths)


